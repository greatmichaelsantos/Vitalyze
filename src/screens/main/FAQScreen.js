// ── Accordion item ─────────────────────────────────────────────────────────────

function AccordionItem({ question, answer, isLast, reduceMotion, colors, styles }) {
  const [expanded, setExpanded] = useState(false);
  const animOpacity = useRef(new Animated.Value(0)).current;

  const toggle = () => {
    if (!expanded) {
      setExpanded(true);
      animOpacity.setValue(0);
      if (reduceMotion) {
        animOpacity.setValue(1);
      } else {
        Animated.timing(animOpacity, {
          toValue: 1,
          duration: 200,
          useNativeDriver: true,
        }).start();
      }
    } else {
      if (reduceMotion) {
        animOpacity.setValue(0);
        setExpanded(false);
      } else {
        Animated.timing(animOpacity, {
          toValue: 0,
          duration: 150,
          useNativeDriver: true,
        }).start(({ finished }) => {
          if (finished) setExpanded(false);
        });
      }
    }
  };

  return (
    <View>
      <TouchableOpacity
        style={styles.itemHeader}
        onPress={toggle}
        accessibilityRole="button"
        accessibilityLabel={question}
        accessibilityState={{ expanded }}
        accessibilityHint={expanded ? 'Tap to collapse this answer' : 'Tap to expand this answer'}
        hitSlop={{ top: 4, bottom: 4, left: 0, right: 0 }}
      >
        <Text
          style={[styles.question, { color: colors.textPrimary }]}
          maxFontSizeMultiplier={1.3}
        >
          {question}
        </Text>
        <Ionicons
          name={expanded ? 'chevron-up' : 'chevron-down'}
          size={18}
          color={colors.textTertiary}
          importantForAccessibility="no"
        />
      </TouchableOpacity>

      {expanded && (
        <Animated.View style={[styles.answerWrap, { opacity: animOpacity }]}>
          <Text
            style={[styles.answer, { color: colors.textSecondary }]}
            maxFontSizeMultiplier={1.5}
          >
            {answer}
          </Text>
        </Animated.View>
      )}

      {!isLast && (
        <View style={[styles.divider, { backgroundColor: colors.border }]} />
      )}
    </View>
  );
}

